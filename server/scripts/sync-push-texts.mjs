// Copies the notification wording from the website translations so a push notification reads exactly like the in-app one.
// Run after changing client/src/i18n/locales/*.json:  node server/scripts/sync-push-texts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const locales = path.resolve(here, "../../client/src/i18n/locales");
const out = {};
for (const code of ["uz", "ru", "en"]) {
  const json = JSON.parse(readFileSync(path.join(locales, `${code}.json`), "utf8"));
  out[code] = { notify: json.notify, type: json.type, customerStatus: json.customerStatus };
}
const body = `// Generated by scripts/sync-push-texts.mjs from the website translations. Do not edit by hand.
export const PUSH_TEXTS = ${JSON.stringify(out, null, 2)} as const;
`;
writeFileSync(path.resolve(here, "../src/lib/pushTexts.generated.ts"), body);
console.log("Wrote src/lib/pushTexts.generated.ts");
